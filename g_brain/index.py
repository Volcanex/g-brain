"""brain-index: compile folder-level topic indexes and a master index.

Usage:
  brain-index compile   # scan all notes, write indexes/
  brain-index           # same as compile
"""

from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

import frontmatter

import g_config

BRAIN_ROOT = g_config.BRAIN_ROOT
INDEXES_DIR = BRAIN_ROOT / "indexes"
# Display order for master index
FOLDER_ORDER = ["designs", "ideas", "about", "hazards"]
KIND_DIRS = set(FOLDER_ORDER)


def _now_iso() -> str:
    return dt.datetime.now().isoformat(timespec="seconds")


def _should_skip(rel: Path) -> bool:
    """Skip dot-prefixed dirs, versions/, archive/, .history/, indexes/."""
    for part in rel.parts[:-1]:
        if part.startswith(".") or part in ("versions", "archive", "indexes"):
            return True
    return False


def collect_notes() -> dict[str, list[dict]]:
    groups: dict[str, list[dict]] = {d: [] for d in KIND_DIRS}
    seen: set[str] = set()  # deduplicate folder-shaped notes (current.md)

    for md in sorted(BRAIN_ROOT.rglob("*.md")):
        rel = md.relative_to(BRAIN_ROOT)
        if _should_skip(rel):
            continue
        parts = rel.parts
        if len(parts) < 2:
            continue
        top = parts[0]
        if top not in KIND_DIRS:
            continue

        # Folder-shaped note: designs/<slug>/current.md
        if md.name == "current.md" and len(parts) == 3:
            slug = parts[1]
            note_path = f"{top}/{slug}/current.md"
            wikilink = slug  # matches how existing notes cross-link: [[audit-signal-architecture]]
        else:
            slug = md.stem
            note_path = str(rel)
            wikilink = slug  # matches how existing notes cross-link: [[brain-future-work]]

        if note_path in seen:
            continue
        seen.add(note_path)

        try:
            post = frontmatter.load(md)
            title = str(post.get("title") or slug)
            status = str(post.get("status", "active"))
            summary = str(post.get("summary", "")).strip()
        except Exception:
            title = slug
            status = "active"
            summary = ""

        groups[top].append({
            "title": title,
            "path": note_path,
            "wikilink": wikilink,
            "status": status,
            "summary": summary,
        })

    return {k: v for k, v in groups.items() if v}


def write_topic_index(folder: str, notes: list[dict]) -> Path:
    INDEXES_DIR.mkdir(exist_ok=True)
    out_path = INDEXES_DIR / f"{folder}.md"

    lines = [
        "---",
        "kind: index",
        f"title: {folder.capitalize()} Index",
        f"covers: {folder}/",
        f"generated_at: {_now_iso()}",
        f"updated: {_now_iso()[:10]}",
        "tags: [auto-generated, index]",
        "---",
        "",
        f"# {folder.capitalize()} Index",
        "",
        "_Auto-generated by brain-index. Do not edit._",
        "",
    ]

    for note in notes:
        wikilink = note["wikilink"]
        status = note["status"]
        summary = note["summary"] or ""
        if len(summary) > 100:
            summary = summary[:97] + "..."
        # Plain [[wikilink]] so basic-memory graph edges resolve correctly.
        # Status badge only when non-active to keep the happy path clean.
        entry = f"- [[{wikilink}]]"
        if status != "active":
            entry += f" `{status}`"
        if summary:
            entry += f": {summary}"
        lines.append(entry)

    out_path.write_text("\n".join(lines) + "\n")
    return out_path


def write_master_index(groups: dict[str, list[dict]]) -> Path:
    INDEXES_DIR.mkdir(exist_ok=True)
    out_path = INDEXES_DIR / "master.md"

    lines = [
        "---",
        "kind: index",
        "title: Brain Master Index",
        f"generated_at: {_now_iso()}",
        f"updated: {_now_iso()[:10]}",
        "tags: [auto-generated, index, master]",
        "---",
        "",
        "# Brain Master Index",
        "",
        "_Auto-generated by brain-index. Read after brain_init to orient._",
        "",
    ]

    for folder in FOLDER_ORDER:
        notes = groups.get(folder)
        if not notes:
            continue
        count = len(notes)
        lines.append(f"## {folder.capitalize()} ({count} notes)")
        lines.append(f"→ [[indexes/{folder}]]")
        lines.append("")
        for note in notes[:3]:
            title = note["title"]
            summary = note["summary"]
            entry = f"- **{title}**"
            if summary:
                short = summary[:80] + ("..." if len(summary) > 80 else "")
                entry += f": {short}"
            lines.append(entry)
        if count > 3:
            lines.append(f"- _…and {count - 3} more_")
        lines.append("")

    out_path.write_text("\n".join(lines) + "\n")
    return out_path


def compile_indexes() -> None:
    groups = collect_notes()
    for folder in FOLDER_ORDER:
        notes = groups.get(folder)
        if not notes:
            continue
        path = write_topic_index(folder, notes)
        print(f"wrote {path.relative_to(BRAIN_ROOT)} ({len(notes)} notes)")
    master = write_master_index(groups)
    total = sum(len(v) for v in groups.values())
    print(f"wrote {master.relative_to(BRAIN_ROOT)} ({total} notes across {len(groups)} folders)")


def main() -> None:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "compile"
    if cmd in ("compile", "view"):
        compile_indexes()
    else:
        print(f"unknown command: {cmd}; choices: compile", file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
